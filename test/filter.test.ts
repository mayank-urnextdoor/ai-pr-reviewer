import { describe, expect, it } from "vitest";
import { filterFiles, isBinaryPath, looksGenerated, parsePatternList } from "../src/filter.js";
import { fileWithAdds } from "./helpers.js";

const defaults = { include: [], exclude: [], skipGenerated: true };

describe("parsePatternList", () => {
  it("splits on newlines and commas and drops blanks and comments", () => {
    expect(parsePatternList("src/**\n  lib/** , \n# comment\n\n*.ts")).toEqual(["src/**", "lib/**", "*.ts"]);
  });
});

describe("filterFiles", () => {
  it("keeps ordinary source files", () => {
    const { kept, skipped } = filterFiles([fileWithAdds("src/app.ts", ["x"])], defaults);
    expect(kept.map((f) => f.path)).toEqual(["src/app.ts"]);
    expect(skipped).toEqual([]);
  });

  it("skips lockfiles anywhere in the tree", () => {
    const files = ["package-lock.json", "web/yarn.lock", "go.sum", "crates/x/Cargo.lock"].map((p) => fileWithAdds(p, ["x"]));
    const { kept, skipped } = filterFiles(files, defaults);
    expect(kept).toEqual([]);
    expect(skipped.every((s) => s.reason === "lockfile")).toBe(true);
  });

  it("skips generated paths, including at the repository root", () => {
    const files = ["dist/index.js", "pkg/vendor/lib.go", "app.min.js", "api/service.pb.go", "src/__snapshots__/a.snap"].map(
      (p) => fileWithAdds(p, ["x"]),
    );
    const { kept, skipped } = filterFiles(files, defaults);
    expect(kept).toEqual([]);
    expect(new Set(skipped.map((s) => s.reason))).toEqual(new Set(["generated"]));
  });

  it("skips files whose header says they are generated", () => {
    const file = fileWithAdds("src/schema.ts", ["// Code generated by protoc-gen-ts. DO NOT EDIT.", "export {}"]);
    expect(looksGenerated(file)).toBe(true);
    expect(filterFiles([file], defaults).skipped).toEqual([{ path: "src/schema.ts", reason: "generated" }]);
  });

  it("only looks for generator markers at the top of the file", () => {
    expect(looksGenerated(fileWithAdds("src/a.ts", ["// @generated"], 40))).toBe(false);
  });

  it("can review lockfiles and generated code when skipGenerated is false", () => {
    const { kept } = filterFiles([fileWithAdds("yarn.lock", ["x"]), fileWithAdds("dist/a.js", ["x"])], {
      ...defaults,
      skipGenerated: false,
    });
    expect(kept).toHaveLength(2);
  });

  it("skips binary, deleted and addition-free files", () => {
    const files = [
      fileWithAdds("logo.png", ["x"]),
      fileWithAdds("blob.dat", [], 1, { binary: true, hunks: [] }),
      fileWithAdds("gone.ts", ["x"], 1, { status: "deleted" }),
      fileWithAdds("moved.ts", [], 1, { status: "renamed", oldPath: "old.ts", hunks: [] }),
    ];
    expect(filterFiles(files, defaults).skipped).toEqual([
      { path: "logo.png", reason: "binary" },
      { path: "blob.dat", reason: "binary" },
      { path: "gone.ts", reason: "deleted" },
      { path: "moved.ts", reason: "no-changes" },
    ]);
  });

  it("applies include globs before exclude globs", () => {
    const files = ["src/a.ts", "src/a.test.ts", "docs/readme.md", ".github/workflows/ci.yml"].map((p) => fileWithAdds(p, ["x"]));
    const { kept, skipped } = filterFiles(files, {
      include: ["src/**", ".github/**"],
      exclude: ["**/*.test.ts"],
      skipGenerated: true,
    });
    expect(kept.map((f) => f.path)).toEqual(["src/a.ts", ".github/workflows/ci.yml"]);
    expect(skipped).toEqual([
      { path: "src/a.test.ts", reason: "excluded" },
      { path: "docs/readme.md", reason: "not-included" },
    ]);
  });
});

describe("isBinaryPath", () => {
  it("matches known binary extensions case-insensitively", () => {
    expect(isBinaryPath("a/B.PNG")).toBe(true);
    expect(isBinaryPath("font.woff2")).toBe(true);
  });

  it("ignores dots in directory names and extensionless files", () => {
    expect(isBinaryPath("v1.png/readme")).toBe(false);
    expect(isBinaryPath("Makefile")).toBe(false);
  });
});
