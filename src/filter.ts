import picomatch from "picomatch";
import type { FileDiff } from "./diff.js";

export type SkipReason =
  | "binary"
  | "deleted"
  | "no-changes"
  | "lockfile"
  | "generated"
  | "excluded"
  | "not-included"
  | "hunk-too-large"
  | "over-budget";

export interface SkippedFile {
  path: string;
  reason: SkipReason;
}

export interface FilterOptions {
  /** If non-empty, only paths matching at least one pattern are reviewed. */
  include: readonly string[];
  /** Paths matching any pattern are skipped. Applied after `include`. */
  exclude: readonly string[];
  /** Skip lockfiles and generated/vendored code (default true). */
  skipGenerated: boolean;
}

export const LOCKFILE_PATTERNS = [
  "**/package-lock.json",
  "**/npm-shrinkwrap.json",
  "**/yarn.lock",
  "**/pnpm-lock.yaml",
  "**/bun.lock",
  "**/bun.lockb",
  "**/Cargo.lock",
  "**/Gemfile.lock",
  "**/composer.lock",
  "**/poetry.lock",
  "**/Pipfile.lock",
  "**/uv.lock",
  "**/go.sum",
  "**/flake.lock",
  "**/packages.lock.json",
  "**/pubspec.lock",
  "**/mix.lock",
  "**/Podfile.lock",
];

export const GENERATED_PATTERNS = [
  "**/dist/**",
  "**/build/**",
  "**/out/**",
  "**/vendor/**",
  "**/node_modules/**",
  "**/third_party/**",
  "**/*.min.js",
  "**/*.min.css",
  "**/*.map",
  "**/*.snap",
  "**/__snapshots__/**",
  "**/*.pb.go",
  "**/*_pb2.py",
  "**/*_pb2_grpc.py",
  "**/*.generated.*",
  "**/*.g.dart",
  "**/*.designer.cs",
  "**/generated/**",
];

const BINARY_EXTENSIONS = new Set([
  "png", "jpg", "jpeg", "gif", "webp", "bmp", "ico", "icns", "tiff", "avif",
  "pdf", "zip", "gz", "tgz", "bz2", "xz", "7z", "rar", "jar", "war",
  "woff", "woff2", "ttf", "otf", "eot",
  "mp3", "mp4", "mov", "avi", "webm", "wav", "ogg", "flac",
  "exe", "dll", "so", "dylib", "a", "o", "class", "pyc", "wasm", "node",
  "sqlite", "db", "bin",
]);

/** Markers that code generators put near the top of their output. */
const GENERATED_MARKERS = [/@generated\b/, /Code generated .* DO NOT EDIT/i, /<auto-generated/i, /^\s*(\/\/|#)\s*AUTO-GENERATED/i];

/** Split an action input of globs separated by newlines or commas. */
export function parsePatternList(raw: string): string[] {
  return raw
    .split(/[\n,]/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0 && !p.startsWith("#"));
}

function matcher(patterns: readonly string[]): (path: string) => boolean {
  if (patterns.length === 0) return () => false;
  return picomatch([...patterns], { dot: true });
}

export function isBinaryPath(path: string): boolean {
  const dot = path.lastIndexOf(".");
  if (dot === -1 || dot < path.lastIndexOf("/")) return false;
  return BINARY_EXTENSIONS.has(path.slice(dot + 1).toLowerCase());
}

/** True if the first added lines of a new file carry a code-generator marker. */
export function looksGenerated(file: FileDiff): boolean {
  const firstHunk = file.hunks[0];
  if (!firstHunk || firstHunk.newStart > 1) return false;
  return firstHunk.lines
    .slice(0, 10)
    .some((l) => l.kind !== "del" && GENERATED_MARKERS.some((re) => re.test(l.content)));
}

export function filterFiles(
  files: readonly FileDiff[],
  options: FilterOptions,
): { kept: FileDiff[]; skipped: SkippedFile[] } {
  const isIncluded = options.include.length > 0 ? matcher(options.include) : () => true;
  const isExcluded = matcher(options.exclude);
  const isLockfile = matcher(LOCKFILE_PATTERNS);
  const isGeneratedPath = matcher(GENERATED_PATTERNS);

  const kept: FileDiff[] = [];
  const skipped: SkippedFile[] = [];
  const skip = (path: string, reason: SkipReason) => skipped.push({ path, reason });

  for (const file of files) {
    const { path } = file;
    if (file.binary || isBinaryPath(path)) skip(path, "binary");
    else if (file.status === "deleted") skip(path, "deleted");
    else if (!file.hunks.some((h) => h.lines.some((l) => l.kind === "add"))) skip(path, "no-changes");
    else if (!isIncluded(path)) skip(path, "not-included");
    else if (isExcluded(path)) skip(path, "excluded");
    else if (options.skipGenerated && isLockfile(path)) skip(path, "lockfile");
    else if (options.skipGenerated && (isGeneratedPath(path) || looksGenerated(file))) skip(path, "generated");
    else kept.push(file);
  }

  return { kept, skipped };
}
